// Synthetic public downloads only. Never reads or converts user files.
import { mkdir, writeFile } from 'node:fs/promises'
import { chromium } from '@playwright/test'

const directory = new URL('../apps/web/public/demo/', import.meta.url)
await mkdir(directory, { recursive: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const assets = {}
try {
  const page = await browser.newPage()
  for (const [format, mimeType] of [
    ['png', 'image/png'],
    ['jpg', 'image/jpeg'],
  ]) {
    const data = await page.locator('body').evaluate((body, mime) => {
      const canvas = body.ownerDocument.createElement('canvas')
      canvas.width = 480
      canvas.height = 160
      const context = canvas.getContext('2d')
      context.fillStyle = '#ffffff'
      context.fillRect(0, 0, canvas.width, canvas.height)
      context.fillStyle = '#20242b'
      context.font = '32px sans-serif'
      context.fillText('DEMO', 24, 56)
      context.font = '18px sans-serif'
      context.fillText('Учебный пример. Конвертации не было.', 24, 104)
      return canvas.toDataURL(mime, 0.9).split(',')[1]
    }, mimeType)
    const bytes = Buffer.from(data, 'base64')
    await writeFile(new URL(`sample.${format}`, directory), bytes)
    assets[format] = {
      mimeType,
      sizeBytes: bytes.length,
      path: `/demo/sample.${format}`,
    }
  }
} finally {
  await browser.close()
}

const stream =
  'BT /F1 20 Tf 36 760 Td (DEMO OUTPUT) Tj 0 -32 Td /F1 12 Tf (Synthetic example. The original file was not converted.) Tj ET'
const objects = [
  '<< /Type /Catalog /Pages 2 0 R >>',
  '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
  '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
  '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
  `<< /Length ${Buffer.byteLength(stream)} >>\nstream\n${stream}\nendstream`,
]
let pdf = '%PDF-1.4\n'
const offsets = [0]
for (const [index, object] of objects.entries()) {
  offsets.push(Buffer.byteLength(pdf))
  pdf += `${index + 1} 0 obj\n${object}\nendobj\n`
}
const xref = Buffer.byteLength(pdf)
pdf += `xref\n0 6\n0000000000 65535 f \n${offsets
  .slice(1)
  .map((n) => `${String(n).padStart(10, '0')} 00000 n \n`)
  .join('')}trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`
await writeFile(new URL('sample.pdf', directory), pdf)
assets.pdf = {
  mimeType: 'application/pdf',
  sizeBytes: Buffer.byteLength(pdf),
  path: '/demo/sample.pdf',
}
await writeFile(
  new URL('../apps/web/src/shared/api/demo-assets.js', import.meta.url),
  `// Generated by scripts/create_demo_fixtures.mjs; public synthetic samples.\nexport const demoAssets = ${JSON.stringify(assets, null, 2)}\n`,
)
